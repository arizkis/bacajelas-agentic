#!/usr/bin/env node
/**
 * Deploy both Firebase Hosting sites with the publisher default wired in.
 *
 * Why staging exists: the live site needs the publisher-funded Otari key
 * available to its browser runtime (spec §4 "Default inference"), but the
 * key must never be committed. So this script copies `site/` and `caller/`
 * into the gitignored `.deploy/` folder, generates the deployed copy of
 * `site/publisher-config.js` there from `.otari-key.txt`, and deploys the
 * staging folder. The repository's own `site/publisher-config.js` stays a
 * null placeholder forever.
 *
 * The key is read from `.otari-key.txt`, used in memory, and written only
 * into `.deploy/`. It is never printed.
 *
 * Usage: node scripts/deploy.mjs [--stage-only]
 */
import { readFileSync, writeFileSync, cpSync, rmSync, mkdirSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const stageOnly = process.argv.includes('--stage-only');

const key = readFileSync(join(root, '.otari-key.txt'), 'utf8').trim();
if (key.length < 10) {
  console.error('ABORT: .otari-key.txt looks empty or truncated. Nothing staged.');
  process.exit(1);
}

// Paranoia gate: refuse to stage a key anywhere git could ever see it.
const gate = spawnSync('git', ['check-ignore', '-q', '.deploy/site/publisher-config.js'], { cwd: root });
if (gate.status !== 0) {
  console.error('ABORT: .deploy/ is not covered by .gitignore. Refusing to stage the key.');
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(join(root, 'site', 'agent-manifest.json'), 'utf8'));
const baseUrl = manifest.llm_router.base_url;
const model = manifest.llm_router.model;

const stage = join(root, '.deploy');
rmSync(stage, { recursive: true, force: true });
mkdirSync(join(stage, 'site'), { recursive: true });
mkdirSync(join(stage, 'caller'), { recursive: true });
cpSync(join(root, 'site'), join(stage, 'site'), { recursive: true });
cpSync(join(root, 'caller'), join(stage, 'caller'), { recursive: true });

const generated = `/* GENERATED by scripts/deploy.mjs at deploy time — gitignored, never commit.
 * Publisher default inference (spec §4): a bounded, revocable
 * registrant-credit key, served with the deployed bundle because a
 * static site has no server side to hold it. Source of truth:
 * .otari-key.txt at the project root (also gitignored). */
export const PUBLISHER_DEFAULT = ${JSON.stringify({ baseUrl, model, apiKey: key }, null, 1)};
`;
writeFileSync(join(stage, 'site', 'publisher-config.js'), generated);
copyFileSync(join(root, 'firebase.json'), join(stage, 'firebase.json'));
copyFileSync(join(root, '.firebaserc'), join(stage, '.firebaserc'));
console.log(`Staged .deploy/ (site + caller) with publisher default: router host ${new URL(baseUrl).host}, model ${model}, key present (length ${key.length}, value not shown).`);

if (stageOnly) {
  console.log('--stage-only: not deploying.');
  process.exit(0);
}

const res = spawnSync('npx', ['--yes', 'firebase-tools', 'deploy', '--only', 'hosting'], {
  cwd: stage, stdio: 'inherit',
});
process.exit(res.status ?? 1);
